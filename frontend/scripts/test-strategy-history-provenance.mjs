import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import {createHash} from 'node:crypto';
const exports = {};
const input = fs.readFileSync(new URL('../src/workspaces/crypto/strategy-history-provenance.ts', import.meta.url), 'utf8');
new Function('exports', ts.transpileModule(input, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText)(exports);
const {shouldRequestSource, validStrategySource, sourceContentHashesMatch, historicalProvenance, filterChartWindow, missingHistoricalSeries} = exports;
assert.deepEqual(missingHistoricalSeries({equity: [{}], drawdown: [{}], trades: [], costs: [], monthly_returns: []}), ['月度收益序列', '完整成交账本', '现金成本分项']);
