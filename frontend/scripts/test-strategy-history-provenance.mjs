const selection = {strategyId: 'top5', candidateId: 'c'};
assert.equal(shouldRequestSource(selection), true, 'unknown catalog capability must resolve through read-only canonical API');
assert.equal(shouldRequestSource({...selection, canonicalSignalAvailable: false}), false);
assert.equal(shouldRequestSource({strategyId: 'top5'}), false);
const source = {strategy_id: 'top5', candidate_id: 'c', canonical_signal_available: true, source_ref: 'registry.py', content: 'def signal(): pass', content_sha256: 'a'.repeat(64), sections: [{symbol: 'signal', source_ref: 'registry.py', content: 'def signal(): pass', content_sha256: 'a'.repeat(64)}], safety: {paper: false, live: false, order: false, private: false, real_order: false}};
assert.equal(validStrategySource(source, selection), true);
assert.equal(validStrategySource({...source, candidate_id: 'other'}, selection), false);
assert.equal(validStrategySource({...source, safety: {...source.safety, private: true}}, selection), false);
assert.equal(validStrategySource({...source, safety: {}}, selection), false);
assert.equal(validStrategySource({...source, canonical_signal_available: false}, selection), false);
assert.equal(await sourceContentHashesMatch(source), false, 'syntactically valid but incorrect digest is rejected');
const actualHash = createHash('sha256').update(source.content).digest('hex');
const hashedSource = {...source, content_sha256: actualHash, sections: source.sections.map(section => ({...section, content_sha256: actualHash}))};
assert.equal(await sourceContentHashesMatch(hashedSource), true);
const meta = historicalProvenance({source: {data: {exchange: 'binance_spot', symbol: 'BTCUSDT', source_interval: '1h', decision_interval: '4h', bar_4h_start: '2024-01-01T11:59:59.999+08:00', bar_4h_end: '2026-06-29T07:59:59.999+08:00'}, generated_at_utc: '2026-06-30T10:18:57+08:00', report_sha256: 'b'.repeat(64), source_code_commit: 'old'}, canonical: {strategy_identity: {execution_venue: 'research_simulation'}}});
assert.equal(meta.exchange, 'Binance 现货');
